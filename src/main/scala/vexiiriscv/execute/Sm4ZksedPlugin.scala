  val mapping = new {
    def KS = 26
    def BYTE_SEL = 31 downto 30
  }

  val logic = during setup new Logic {
    awaitBuild()
    assert(Riscv.XLEN.get == 32 || Riscv.XLEN.get == 64)
    import SrcKeys._

    val wb = newWriteback(ifp, writeBackAt)
    for (op <- List(Rvk.SM4ED, Rvk.SM4KS)) {
      add(op).srcs(SRC1.RF, SRC2.RF)
      ifp.signExtend(wb, layer(op), 32)
    }
    uopRetainer.release()

    val onRead = new el.Execute(readAt) {
      val byteSel = Decode.UOP(mapping.BYTE_SEL).asUInt
      val bankSel = Decode.UOP(mapping.KS)
      val selByte = up(el(IntRegFile, RS2)).asBits(31 downto 0).subdivideIn(8 bits).read(byteSel)
      val romAddress = U(bankSel ## selByte)
    }

    val onData = new el.Execute(readAt + 1) {
      val rom = new Area {
        val storage = Mem(Bits(32 bits), 512) initBigInt((ED ++ KS).map(BigInt(_)))
        val data = storage.readSync(onRead.romAddress, isReady)
      }

      val byteSel = Decode.UOP(30, 2 bits).asUInt
      val rotated = byteSel.mux(
        0 -> rom.data,
        1 -> rom.data.rotateLeft(8),
        2 -> rom.data.rotateLeft(16),
        3 -> rom.data.rotateLeft(24)
      )
      val rs1 = up(el(IntRegFile, RS1)).asBits(31 downto 0)

      val RESULT = insert(rotated ^ rs1)
    }

    val writeback = new el.Execute(writeBackAt) {
      wb.valid := SEL
      wb.payload := onData.RESULT.resized
    }
  }

